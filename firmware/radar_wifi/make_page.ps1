# monitor\index.html 을 펌웨어에 넣을 page.h 로 바꿉니다. index.html을 고친 뒤 다시 실행하세요.
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$html = [IO.File]::ReadAllText((Join-Path $root '..\..\monitor\index.html'), [Text.Encoding]::UTF8)
if ($html.Contains(')RAWPAGE"')) { throw 'index.html contains the raw-string delimiter' }
$h = "#pragma once`n// Generated by make_page.ps1 from monitor/index.html. Do not edit.`nconst char PAGE_HTML[] PROGMEM = R`"RAWPAGE(" + $html + ")RAWPAGE`";`n"
[IO.File]::WriteAllText((Join-Path $root 'page.h'), $h, (New-Object Text.UTF8Encoding($false)))
"page.h: $($html.Length) chars"
